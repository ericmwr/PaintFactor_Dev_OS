// One-time (re-runnable) generator for src/data/scenario-rate-data.js — the
// scenario-owned home for the material/protection/QT data that P3 relocates out
// of the SQLite-generated db-bundle.js (deleted in Phase 6). Committed as the
// regeneration tool; the generated module is the runtime source of truth.
// Run: npx vite-node scripts/build-scenario-rate-data.mjs
import { writeFileSync } from 'node:fs';
import { DB_BUNDLE } from '../src/data/db-bundle.js';

// Project rows to a fixed key set. Missing source keys default to null so every
// projected row has an identical shape (e.g. sop_tasks without protection_metadata
// still carry the key, as null).
const pick = (rows, keys) =>
  (rows || []).map(r => Object.fromEntries(keys.map(k => [k, r[k] ?? null])));

const out = {
  MATERIAL_SYSTEMS:           DB_BUNDLE.material_systems || [],
  MATERIAL_COVERAGE_PROFILES: DB_BUNDLE.material_coverage_profiles || [],
  MATERIAL_SYSTEM_PRODUCTS:   DB_BUNDLE.material_system_products || [],
  QUALITY_TIER_EFFECTS:       DB_BUNDLE.quality_tier_effects || [],
  SPEC_PROTECTION_ZONES:      DB_BUNDLE.spec_protection_zones || [],
  // Projection — protection only needs protection_metadata, indexed by id::spec_family_id.
  SOP_TASK_PROTECTION:        pick(DB_BUNDLE.sop_tasks, ['id', 'spec_family_id', 'protection_metadata']),
  // Projection — the engine only needs spec display name + domain.
  SPEC_FAMILY_INFO:           pick(DB_BUNDLE.spec_families, ['id', 'name', 'domain']),
};

const banner = `// AUTO-GENERATED by scripts/build-scenario-rate-data.mjs — do not hand-edit.
// Scenario-owned relocation of material/protection/QT data (P3, spec-system
// retirement). Frozen snapshot from db-bundle.js; the SQLite spec tables it came
// from are deleted in Phase 6. Re-run the generator if the source data changes.
`;
const body = Object.entries(out)
  .map(([name, rows]) => `export const ${name} = ${JSON.stringify(rows, null, 2)};`)
  .join('\n\n');

writeFileSync(new URL('../src/data/scenario-rate-data.js', import.meta.url), banner + '\n' + body + '\n');
console.log('Wrote src/data/scenario-rate-data.js');
for (const [name, rows] of Object.entries(out)) console.log(`  ${name}: ${rows.length} rows`);
